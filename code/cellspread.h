	// The number of table entries that lie within the radius, which is limited to 0 through CELL_SPREAD_MAX.
	inline int Count(int radius)
	{
		static int const counts[CELL_SPREAD_MAX + 1] = {1, 9, 21, 37, 61, 89, 121, 161, 205, 253, 309, 369};
		return(counts[std::clamp(radius, 0, CELL_SPREAD_MAX)]);
	}

	// The radius, in whole cells, that a warhead's CellSpread reaches: the spread rounded up, except
	// that a fraction of about 0.01 over a whole number does not reach the next cell. The result is
	// held between 0 and CELL_SPREAD_MAX.
	inline int Radius_For(float cell_spread)
	{
		return(std::clamp((int)(cell_spread + 0.99f), 0, CELL_SPREAD_MAX));
	}
