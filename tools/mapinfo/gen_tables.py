#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Writes tools/mapinfo/tables.inc from the engine's own source, so that mapinfo names and
# parameter kinds cannot drift from the game:
#
#   code/tevent.hh     TEventType enumerators         -> event names
#   code/taction.hh    TActionType enumerators        -> action names
#   code/tmission.hh   TeamMissionType enumerators    -> team mission (script action) names
#   code/tevent.cpp    Event_Needs() case table       -> what each event's parameter is
#   code/taction.cpp   Action_Needs() case table      -> what each action's parameter is
#   code/tmission.cpp  TeamMission_Needs() case table -> what each team mission's parameter is
#   code/taction.cpp   ParamCodeType                  -> the first field of an action
#
# The numbers and the names come from the enumerators, so a renamed or renumbered engine
# enumerator fails to build the tool, and a new one is picked up on the next run. Run
# without arguments to rewrite tables.inc; run with --check to exit 1 when it is stale (the
# ctest mapinfo-tables-current test does this).

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "tools" / "mapinfo" / "tables.inc"

ENUM_SOURCES = [
    ("TEVENT_", ROOT / "code" / "tevent.hh", "TEventType", "events", "kEventNames"),
    ("TACTION_", ROOT / "code" / "taction.hh", "TActionType", "actions", "kActionNames"),
    ("TMISSION_", ROOT / "code" / "tmission.hh", "TeamMissionType", "team missions", "kTeamMissionNames"),
]

NEED_SOURCES = [
    ("Event_Needs", ROOT / "code" / "tevent.cpp", "kEventNeeds", "NeedType Event_Needs("),
    ("Action_Needs", ROOT / "code" / "taction.cpp", "kActionNeeds", "NeedType Action_Needs("),
    ("TeamMission_Needs", ROOT / "code" / "tmission.cpp", "kTeamMissionNeeds", "NeedType TeamMission_Needs("),
]

PARAM_SOURCE = ROOT / "code" / "taction.cpp"


def strip_comments(line):
    """Removes // comments and /* */ comments that sit on one line."""
    line = re.sub(r"/\*.*?\*/", "", line)
    cut = line.find("//")
    return line[:cut] if cut >= 0 else line


def read_lines(path):
    return path.read_text(encoding="utf-8", errors="replace").splitlines()


def enum_body(lines, enum_name):
    """Returns the enumerator names of enum enum_name, in order, with their explicit values."""
    start = None
    for index, line in enumerate(lines):
        if re.match(r"\s*enum\s+" + re.escape(enum_name) + r"\b", line):
            start = index
            break
    if start is None:
        sys.exit("gen_tables: enum %s not found" % enum_name)
    names = []
    for line in lines[start + 1:]:
        text = strip_comments(line).strip()
        if text.startswith("}"):
            break
        match = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*(=\s*[^,]+)?\s*,?\s*$", text)
        if match:
            names.append((match.group(1), match.group(2)))
    return names


def function_body(lines, signature):
    """Returns the lines between a function's signature and its closing brace at column 0."""
    start = None
    for index, line in enumerate(lines):
        if line.startswith(signature):
            start = index
            break
    if start is None:
        sys.exit("gen_tables: function starting %r not found" % signature)
    body = []
    for line in lines[start + 1:]:
        if line.startswith("}"):
            break
        body.append(line)
    return body


def need_table(lines, signature, prefix):
    """Maps each enumerator labelled in the switch to the NEED_ value its case returns."""
    result = {}
    pending = []
    for raw in function_body(lines, signature):
        text = strip_comments(raw).strip()
        if not text or text.startswith("//") or text.startswith("*") or text.startswith("/*"):
            continue
        for label in re.findall(r"case\s+(" + prefix + r"[A-Za-z0-9_]+)\s*:", text):
            pending.append(label)
        returned = re.search(r"return\(\s*(NEED_[A-Za-z0-9_]+)\s*\)", text)
        if returned:
            for label in pending:
                result[label] = returned.group(1)
            pending = []
    return result


def fmt_enum_table(values):
    rows = ["\t{%s, \"%s\"}," % (name, name.split("_", 1)[1]) for name, _ in values if name.endswith("_NONE") is False or True]
    return rows


def build():
    out = []
    out.append("// Generated by tools/mapinfo/gen_tables.py from the engine sources. Do not edit by hand.")
    out.append("// Run `python tools/mapinfo/gen_tables.py` after changing the engine and commit the result.")
    out.append("")

    # The first field of an action in a map says what kind of parameter the second field holds.
    param_lines = read_lines(PARAM_SOURCE)
    params = enum_body(param_lines, "ParamCodeType")
    out.append("/// The kind of the second field of an action, from ParamCodeType in code/taction.cpp.")
    out.append("enum MapParamCode {")
    for name, value in params:
        out.append("\t%s%s," % (name, " " + value.strip() if value else ""))
    out.append("};")
    out.append("")

    for prefix, path, enum_name, label, table in ENUM_SOURCES:
        values = enum_body(read_lines(path), enum_name)
        names = [name for name, _ in values if not name.endswith("_COUNT") and not name.endswith("_FIRST")]
        out.append("/// The names of all %s, from the enumerators in %s." % (label, path.relative_to(ROOT).as_posix()))
        out.append("static MapNameEntry const %s[] = {" % table)
        for name in names:
            out.append("\t{%s, \"%s\"}," % (name, name[len(prefix):]))
        out.append("};")
        out.append("")

    for function, path, table, signature in NEED_SOURCES:
        lines = read_lines(path)
        prefix = {"Event_Needs": "TEVENT_", "Action_Needs": "TACTION_", "TeamMission_Needs": "TMISSION_"}[function]
        needs = need_table(lines, signature, prefix)
        out.append("/// What %s returns for each case that names a parameter kind, from %s." % (function, path.relative_to(ROOT).as_posix()))
        out.append("static MapNeedEntry const %s[] = {" % table)
        for label in needs:
            out.append("\t{%s, %s}," % (label, needs[label]))
        out.append("};")
        out.append("")

    return "\n".join(out) + "\n"


def main(argv):
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("gen_tables: %s is stale; run python tools/mapinfo/gen_tables.py" % OUT.relative_to(ROOT).as_posix())
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("gen_tables: wrote %s" % OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
